/// Сколько лакомых мест держать одновременно.
pub const FEAST_COUNT: usize = 3;

/// Радиус, в котором лакомое место сыплет еду.
pub const FEAST_RADIUS: f32 = 9.0;

/// Сколько живёт одно лакомое место, секунд.
pub const FEAST_LIFETIME: f32 = 55.0;

/// Какая доля еды сыплется в лакомые места, а не по всей арене.
///
/// Не вся: если бы вне пятен еды не было совсем, игра свелась бы к трём точкам
/// на карте, и всё остальное море стало бы мёртвым коридором.
pub const FEAST_SHARE: f32 = 0.62;

/// Место, где сейчас особенно много еды.
///
/// Смысл в том, чтобы у моря была причина куда-то плыть. Равномерно рассыпанная
/// еда никуда не зовёт: где стоишь, там и корм. Пятно — это повод рискнуть,
/// потому что туда же приплывут и остальные.
#[derive(Component, Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub struct Feast {
    pub position: Vec3,
    pub radius: f32,
    /// Сколько ему осталось, в долях от полной жизни: клиент рисует по этому
    /// числу яркость, чтобы затухающее пятно было видно заранее.
    pub strength: f32,
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Главное свойство куста: мелкий прячется, крупный не проходит.
    ///
    /// Меряется по **настоящим** телам, а не по `body_radius(BASE_MASS)`.
    /// Прошлая версия теста считала тело без единого органа — такого в игре не
    /// бывает, стартовый геном всегда несёт мембрану, жгутик и рот, — и из-за
    /// этого пропустила порог, при котором куст резал вообще всех.
    #[test]
    fn a_thorn_is_shelter_for_the_small_and_a_wall_for_the_big() {
        use crate::{body_radius, random_part, Genome, OrganismState};

        let grown_to = |parts: usize| {
            let mut genome = Genome::starter_of(1);
            for i in 3..parts {
                genome.push_part(random_part(i as u64 * 7919));
            }
            body_radius(OrganismState::from_genome(genome).mass)
        };

        // Новорождённый обязан прятаться: укрытие существует ради него.
        assert!(!Thorn::hurts(grown_to(3)), "стартовое тело не помещается в куст");
        // И ещё какое-то время после: иначе укрытие теряется на первой же мутации.
        assert!(!Thorn::hurts(grown_to(8)), "укрытие кончается слишком рано");

        // Крупное тело уже не проходит.
        assert!(Thorn::hurts(grown_to(25)), "выросшее тело проходит сквозь куст");

        // В куст должно влезать сразу несколько мелких, иначе это не укрытие.
        assert!(
            THORN_RADIUS > grown_to(3) * 4.0,
            "куст меньше четырёх новорождённых: прятаться в нём негде"
        );
    }

    #[test]
    fn hazards_reach_exactly_as_far_as_their_radius() {
        let thorn = Thorn { position: Vec3::ZERO, radius: 2.0 };
        assert!(thorn.touches(Vec3::new(2.5, 0.0, 0.0), 1.0));
        assert!(!thorn.touches(Vec3::new(3.5, 0.0, 0.0), 1.0));


    }
}
