//! Опасности, которые не являются живыми организмами.
//!
//! Колючки стоят на месте и наказывают за размер. Левиафаны проплывают мимо и
//! наказывают за невнимательность. Общее у них одно: это не участники игры, а
//! свойства моря, и вести себя как организмы им не нужно — ни есть, ни
//! размножаться, ни драться по правилам родства.

use bevy::prelude::*;
use serde::{Deserialize, Serialize};

// ─────────────────────────────────────────────
// Колючки
// ─────────────────────────────────────────────

/// Сколько колючек держать в море.
pub const THORN_COUNT: usize = 14;

/// Радиус куста.
///
/// Куст, а не шип: внутри должно помещаться несколько мелких тел сразу, иначе
/// прятаться в нём негде и вся механика сводится к «не подплывай».
/// Стартовое тело имеет радиус около 1.16, то есть в куст их влезает пяток.
pub const THORN_RADIUS: f32 = 5.5;

/// Радиус тела, начиная с которого куст становится опасным.
///
/// Мелкие проплывают насквозь и прячутся внутри — это и есть смысл механики:
/// у слабых появляется место, куда сильный не может за ними последовать.
///
/// Стояло 1.15, и это было ошибкой ровно на одну сотую: **стартовое тело имеет
/// радиус 1.16**, то есть куст резал вообще всех, включая тех, ради кого он
/// существует. Ошибку пропустил тест — он мерил `body_radius(BASE_MASS)`, тело
/// вовсе без органов, которого в игре не бывает: стартовый геном всегда несёт
/// мембрану, жгутик и рот.
///
/// Теперь порог взят от настоящей прогрессии: прячутся тела примерно до
/// пятнадцати органов, крупнее — режутся. См. `examples/balance.rs`, раздел
/// про колючки: он печатает таблицу по настоящим телам.
pub const THORN_SAFE_RADIUS: f32 = 1.45;

/// Урон в секунду тому, кто слишком велик, чтобы пройти насквозь.
pub const THORN_DAMAGE: f32 = 9.0;

/// Неподвижная колючка: убежище для мелких, стена для крупных.
#[derive(Component, Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub struct Thorn {
    pub position: Vec3,
    pub radius: f32,
}

impl Thorn {
    /// Достаёт ли колючка до тела такого размера в такой точке.
    pub fn touches(&self, point: Vec3, body_radius: f32) -> bool {
        let reach = self.radius + body_radius;
        self.position.distance_squared(point) < reach * reach
    }

    /// Опасна ли колючка телу такого размера.
    ///
    /// Ровно один порог, без промежуточных состояний: игрок должен уметь
    /// посмотреть на себя и сказать «мне туда можно» или «мне туда нельзя».
    pub fn hurts(body_radius: f32) -> bool {
        body_radius > THORN_SAFE_RADIUS
    }
}

// ─────────────────────────────────────────────
// Левиафаны
// ─────────────────────────────────────────────

/// Радиус туши.
pub const LEVIATHAN_RADIUS: f32 = 6.5;

/// Скорость: быстрее любой клетки, но не настолько, чтобы нельзя было уйти
/// с дороги, заметив вовремя.
pub const LEVIATHAN_SPEED: f32 = 7.5;

/// Урон в секунду тому, кого он задел.
pub const LEVIATHAN_DAMAGE: f32 = 45.0;

/// Средний промежуток между заплывами, секунд.
pub const LEVIATHAN_INTERVAL: f32 = 95.0;

/// На каком расстоянии чудовище замечает добычу и сворачивает к ней.
///
/// Больше собственного радиуса, но далеко не через всю карту: оно не охотник, а
/// проходящее мимо существо, которое лениво подбирает то, что оказалось близко.
pub const LEVIATHAN_INTEREST: f32 = 26.0;

/// Насколько круто оно способно доворачивать, радиан в секунду.
///
/// Медленно: от туши, разворачивающейся как истребитель, невозможно уйти, и
/// событие «мимо прошёл кто-то огромный» превратилось бы в казнь.
pub const LEVIATHAN_TURN: f32 = 0.32;

/// Сколько детрита остаётся от съеденного чудовищем.
///
/// Оно ест неаккуратно: часть добычи достаётся тем, кто держался в стороне.
/// Это и делает его проход событием, а не просто опасностью — после него есть
/// чем поживиться.
pub const LEVIATHAN_LEFTOVERS: usize = 9;

/// Огромное существо, проплывающее через море насквозь.
///
/// Приходит извне и уходит вдаль: не житель арены, а событие. С ним нельзя
/// драться и его нельзя съесть, зато оно вполне может съесть тебя — и по пути
/// подворачивает к тому, что заметило.
#[derive(Component, Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub struct Leviathan {
    pub position: Vec3,
    /// Единичный вектор курса.
    pub heading: Vec3,
    pub radius: f32,
    /// Растёт, когда оно ест. Клиент раздувает по этому числу брюхо, а сервер
    /// использует его же, чтобы наевшееся чудовище теряло интерес.
    pub fed: f32,
    /// Фаза движения хвоста: считается на сервере, чтобы все видели одно и то
    /// же существо, а не каждый своё.
    pub swim: f32,
}

impl Leviathan {
    pub fn touches(&self, point: Vec3, body_radius: f32) -> bool {
        let reach = self.radius + body_radius;
        self.position.distance_squared(point) < reach * reach
    }

    /// Наелось ли оно настолько, чтобы перестать сворачивать за добычей.
    ///
    /// Сытое чудовище просто уходит: иначе один заплыв выкашивал бы всё море.
    pub fn sated(&self) -> bool {
        self.fed >= 3.0
    }
}

