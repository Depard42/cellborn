/// Полный список органов: что даёт каждый и по какой механике.
///
/// Собирается из таблицы, которой считает сама игра, — справочник не может
/// разойтись с правилами.
pub fn organs_reference() -> String {
    let mut text = String::from(
        "Двадцать органов. Цена указана базовая — в игре она растёт с каждой\n\
отращенной частью. «Снаружи» значит, что орган виден на мембране, «внутри» —\n\
что он плавает в цитоплазме.\n\nОдного органа можно иметь не больше шести.\n"
    );
    for family in PartFamily::ALL {
        let kind = PartKind::basic(family);
        let stats = stats(kind);
        text.push_str(&format!(
            "\n─── {} ───\n{}\nцена {}   масса {:.1}   содержание {:.2}/с   {}\nдаёт: {}\n",
family.name().to_uppercase(),
family.tradeoff(),
stats.cost,
stats.mass,
stats.upkeep,
if family.is_external() { "снаружи" } else { "внутри" },
effect_summary(kind),
        ));
        text.push_str(mechanic_of(family));
    }
    text
}

