//! Текст живёт отдельно от разметки: разделы — это данные, а экран их просто
//! рисует. Так справочник можно дополнять, не трогая интерфейс.

use cellborn_common::*;

pub struct Section {
    pub title: &'static str,
    pub body: Body,
}

/// Текст раздела: либо написанный, либо собранный из настоящих чисел игры.
pub enum Body {
    Static(&'static str),
    Generated(fn() -> String),
}

impl Section {
    pub fn text(&self) -> String {
        match self.body {
            Body::Static(text) => text.to_string(),
            Body::Generated(make) => make(),
        }
    }
}

